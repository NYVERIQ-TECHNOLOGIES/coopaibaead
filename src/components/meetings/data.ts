import { supabase } from "@/integrations/supabase/client";
import type { Database } from "@/integrations/supabase/types";

export type Meeting = Database["public"]["Tables"]["meetings"]["Row"] & { provider?: string | null };
export type Person = { user_id: string; full_name: string; cpf?: string | null; enrollment_number?: string | null; email?: string | null };
export const meetingUrl = (token: string) => `${window.location.origin}/reuniao/${token}`;
export const when = (date: string) => new Date(date).toLocaleString("pt-BR", { dateStyle: "short", timeStyle: "short" });
export const statusText: Record<string, string> = { agendada: "Agendada", em_andamento: "Em andamento", encerrada: "Encerrada", cancelada: "Cancelada" };
export async function loadPeople() {
  const rows: Person[] = [];
  for (let offset = 0; ; offset += 500) {
    const { data, error } = await supabase.from("profiles").select("user_id,full_name,cpf,enrollment_number").order("full_name").range(offset, offset + 499);
    if (error) throw error;
    rows.push(...(data ?? []));
    if (!data || data.length < 500) break;
  }
  return rows;
}
export async function loadMeetingRoles() {
  const rows: { user_id: string; role: string }[] = [];
  for (let offset = 0; ; offset += 500) {
    const { data, error } = await supabase.from("user_roles").select("user_id,role").order("user_id").range(offset, offset + 499);
    if (error) throw error;
    rows.push(...(data ?? []));
    if (!data || data.length < 500) break;
  }
  return rows;
}
export async function callMeeting<T>(name: string, args: Record<string, unknown>): Promise<T> {
  // Meeting RPCs are generated by the database; the dynamic call avoids cross-version type lag.
  const { data, error } = await supabase.rpc(name as "meeting_join", args as never);
  if (error) throw error;
  return data as T;
}
